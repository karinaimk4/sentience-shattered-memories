const { chromium } = require('./playwright-runtime.cjs');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

(async()=>{
  const browser=await chromium.launch({channel:'msedge',headless:true});
  const page=await browser.newPage({viewport:{width:1920,height:1080}});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
  await page.goto('http://127.0.0.1:4181/event-v3.html');
  await page.waitForFunction(()=>window.__TAIXUAN_QA__&&window.__TAIXUAN_WORLD__);
  const loadedAssets=await page.evaluate(()=>window.__TAIXUAN_QA__.snapshot().assets);
  assert.deepEqual(loadedAssets.sort(),['senti','fuhua','rozaliya','susannah','elysia','liliya','carole','seele','veliona','kiana','yae','mei','griseo','bronya','himeko','pardofelis','sushang','guestChild','guestFemale','guestMale'].sort());
  assert(await page.locator('#rush-canvas').isVisible());
  assert.equal(await page.locator('.phase-tabs button').count(),4);
  assert.equal(await page.locator('.control-tabs button').count(),5);
  const qaDir=path.join(__dirname,'..','qa','event-v3-integrated');fs.mkdirSync(qaDir,{recursive:true});
  await page.screenshot({path:path.join(qaDir,'event-v3-lv1-assets-clean.png'),fullPage:true});
  await page.locator('[data-phase="morning"]').click();
  assert(await page.locator('#phase-screen').isVisible());
  assert.equal(await page.locator('.phase-screen-card').count(),4);
  await page.locator('[data-phase="evening"]').click();
  assert(await page.locator('#rush-canvas').isVisible());
  await page.locator('[data-panel="staff"]').click();
  assert(await page.locator('.staff-gacha-banner').isVisible());
  assert.equal(await page.locator('#gacha-ten').count(),0);
  await page.locator('#gacha-one').click();
  await page.locator('#gacha-modal:not([hidden])').waitFor();
  assert.equal(await page.locator('.gacha-result-card').count(),1);
  assert.equal((await page.evaluate(()=>window.__TAIXUAN_QA__.gacha().lastResults)).length,1);
  await page.screenshot({path:path.join(qaDir,'event-v3-gacha-1-pull.png'),fullPage:true});
  await page.locator('#gacha-close').click();
  await page.evaluate(()=>window.__TAIXUAN_QA__.previewGacha(['himeko','elysia','seele','bronya','mei']));
  assert.equal(await page.locator('.gacha-card-fallback').count(),0);
  await page.screenshot({path:path.join(qaDir,'event-v3-gacha-missing-five-assets.png'),fullPage:true});
  await page.locator('#gacha-close').click();
  await page.selectOption('#reception-select','elysia');
  await page.selectOption('#server-select','seele');
  await page.selectOption('#chef-select','mei');
  await page.selectOption('#cleaner-select','bronya');
  await page.keyboard.press('g');
  await page.locator('#level-btn').click();
  await page.waitForFunction(()=>{const ids=window.__TAIXUAN_QA__.snapshot().staff.map(staff=>staff.id);return ['elysia','seele','mei','bronya'].every(id=>ids.includes(id));});
  await page.locator('#level-btn').click();
  await page.keyboard.press('g');
  await page.locator('[data-panel="decor"]').click();
  assert.equal(await page.locator('.decor-shop-card').count(),19);
  assert.equal(await page.evaluate(()=>window.__TAIXUAN_QA__.decorCatalog().filter(item=>item.loaded).length),19);
  await page.locator('[data-decor-id="bonsai"] button').click();
  await page.locator('[data-decor-id="bonsai"] button').click();
  assert.deepEqual(await page.evaluate(()=>window.__TAIXUAN_QA__.decorState()),{owned:['bonsai'],placed:['bonsai']});
  assert.equal(await page.evaluate(()=>window.__TAIXUAN_QA__.moveDecor('bonsai',[14,11])),true);
  await page.locator('#decor-edit-toggle').click();
  assert(await page.locator('#rush-canvas').evaluate(canvas=>canvas.classList.contains('decor-editing')));
  await page.locator('#decor-edit-toggle').click();
  await page.evaluate(()=>window.__TAIXUAN_QA__.setWallet(10000,50));
  await page.locator('#restaurant-upgrade').click();
  await page.waitForFunction(()=>window.__TAIXUAN_QA__.snapshot().roomId==='room2');
  assert.deepEqual(await page.evaluate(()=>({rooms:window.__TAIXUAN_QA__.rooms(),kitchens:window.__TAIXUAN_QA__.snapshot().kitchenSlots,tables:window.__TAIXUAN_QA__.snapshot().tables.length})),{
    rooms:{active:'room2',unlocked:['room1','room2'],cached:{room1:true,room2:true},followCharacter:true,selectedCharacterId:'senti'},kitchens:3,tables:6
  });
  await page.screenshot({path:path.join(qaDir,'event-v3-room2-unlocked.png'),fullPage:true});
  await page.locator('#speed-btn').click();
  await page.evaluate(()=>window.__TAIXUAN_WORLD__.speed=2);
  await page.waitForFunction(()=>window.__TAIXUAN_QA__.snapshot().staff.some(staff=>staff.carry),null,{timeout:20000});
  await page.screenshot({path:path.join(qaDir,'event-v3-carry-dish.png'),fullPage:true});
  await page.evaluate(()=>window.__TAIXUAN_WORLD__.speed=10);
  await page.waitForFunction(()=>window.__TAIXUAN_QA__.snapshot().metrics.completedJobs>2,null,{timeout:12000});
  await page.screenshot({path:path.join(qaDir,'event-v3-service-animation.png'),fullPage:true});
  await page.keyboard.press('g');
  assert(await page.locator('#debug-drawer').isVisible());
  await page.screenshot({path:path.join(qaDir,'event-v3-integrated-shell.png'),fullPage:true});
  assert.deepEqual(errors,[]);
  console.log(JSON.stringify({result:'PASS',screenshot:'qa/event-v3-integrated/event-v3-integrated-shell.png'}));
  await browser.close();
})().catch(error=>{console.error(error);process.exitCode=1;});
