const {chromium}=require('./playwright-runtime.cjs');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');

(async()=>{
 const browser=await chromium.launch({channel:'msedge',headless:true});
 const page=await browser.newPage({viewport:{width:1280,height:900}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 const base=(process.env.HOS_BASE_URL||'http://127.0.0.1:4192/build-assets-v4').replace(/\/$/,'');
 const save=JSON.parse(fs.readFileSync(path.join(__dirname,'../qa/Hanh-trinh-Chuong-5.json'),'utf8')).save;
 save.storyEvents=['ch5-opening','ch5-combat-v3-migrated','ch5-branch-a'];
 await page.goto(base+'/?qa=1');
 await page.waitForFunction(()=>window.__qa?.ready);
 await page.evaluate(value=>localStorage.setItem('sentience-gameplay-v4-save-20260926',JSON.stringify(value)),save);
 await page.reload();await page.waitForFunction(()=>window.__qa?.ready);
 await page.locator('#story').click();await page.evaluate(()=>__qa.manual());
 assert.equal((await page.evaluate(()=>__qa.snapshot())).phase,'explore');
 await page.locator('#game').click();
 const tap=async key=>{await page.keyboard.down(key);await page.keyboard.up(key);};
 await tap('2');await page.evaluate(()=>__qa.step([],1));
 assert.equal((await page.evaluate(()=>__qa.snapshot())).save.weapon,'spear','quick weapon tap must register');
 const before=await page.evaluate(()=>__qa.snapshot());
 await tap('j');await page.evaluate(()=>__qa.step([],1));
 assert.equal((await page.evaluate(()=>__qa.snapshot())).metrics.swings,before.metrics.swings+1,'quick attack tap must register');
 await tap('3');await page.evaluate(()=>__qa.step([],1));
 assert((await page.locator('[data-weapon="chain"]').innerText()).includes('CHỜ ĐỔI'),'weapon switch during an attack must be queued visibly');
 await page.evaluate(()=>__qa.step([],35));
 assert.equal((await page.evaluate(()=>__qa.snapshot())).save.weapon,'chain','queued weapon must equip after attack');
 const x=(await page.evaluate(()=>__qa.snapshot())).p.x;
 await tap('d');await page.evaluate(()=>__qa.step([],7));
 assert((await page.evaluate(()=>__qa.snapshot())).p.x>x+10,'quick move tap must visibly move');
 await tap('s');await page.evaluate(()=>__qa.step([],1));
 assert.equal((await page.evaluate(()=>__qa.snapshot())).p.slide,true,'quick slide tap must register');
 await page.evaluate(()=>__qa.seek(5780));
 const nodeGuide=await page.locator('#combat-guide').innerText();
 assert(nodeGuide.includes('1 · KIẾM'),'node guide must name the actual weapon key');
 await page.evaluate(()=>__qaStartArena(5700));
 const s=await page.evaluate(()=>__qa.snapshot());
 assert.equal(s.enemies.find(e=>e.ai?.type==='seven-swords')?.ai.encounter,'branch-a',JSON.stringify({phase:s.phase,dialogueIndex:s.dialogueIndex,arena:s.arena?.m,scene:s.scene,events:s.storyEvents.slice(-8),enemies:s.enemies.map(e=>e.kind)}));
 const bossGuide=await page.locator('#combat-guide').innerText();
 assert(bossGuide.includes('K phản đòn')&&bossGuide.includes('2 lần'),'boss guide must explain the parry step');
 await page.locator('#play').screenshot({path:path.join(__dirname,'../qa/ch5-controls-guide.png')});
 await page.evaluate(()=>__qaStartArena(5985));
 assert((await page.locator('#combat-guide').innerText()).includes('3 XÍCH'),'branch B guide must explain chain attacks');
 await page.evaluate(()=>__qaStartArena(6270));
 assert((await page.locator('#combat-guide').innerText()).includes('1 KIẾM + J, 2 THƯƠNG + J, 3 XÍCH + J'),'branch C guide must explain the weapon rotation');
 await page.evaluate(()=>__qaStartArena(6580));
 assert((await page.locator('#combat-guide').innerText()).includes('L né 6 đòn đầu'),'formation guide must explain round one');
 await page.evaluate(()=>__qaStartArena(6580,2));
 assert((await page.locator('#combat-guide').innerText()).includes('2 chọn THƯƠNG'),'phantom guide must explain armor break');
 await page.evaluate(()=>__qaStartChapterFiveBowl());
 await tap('e');await page.evaluate(()=>__qa.step([],1));
 assert.equal((await page.evaluate(()=>__qa.snapshot())).memoryTrial.step,1,'quick interact tap must register');
 assert.deepEqual(errors,[]);
 await browser.close();
 console.log(JSON.stringify({ok:true,quickWeapon:true,queuedWeapon:true,quickAttack:true,quickMove:true,quickSlide:true,quickInteract:true,nodeGuide,bossGuide}));
})().catch(error=>{console.error(error);process.exit(1)});
